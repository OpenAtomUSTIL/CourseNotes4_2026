#include <stdio.h>

int main() {
    int arr[5] = {1, 2, 3, 4, 5};
    int *p = arr; // 指针指向数组的首元素，即arr 等价于 &arr[0]
    int i;
    for (i = 0; i < 5; i++) {
        printf("arr[%d] = %d\n", i, *(p + i)); // 使用指针访问数组元素
    }
    return 0;
}